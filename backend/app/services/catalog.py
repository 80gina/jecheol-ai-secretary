def info(name: str) -> dict[str, Any]:
    """품목 하나의 도메인 지식 전부. 모르는 이름이어도 빈손으로 돌려보내지 않는다."""
    name = (name or "").strip()
    major, mid, minor, season, prefer, prep, purpose = ITEMS.get(name, UNKNOWN)
    fresh, difficulty, convenience, fx, weather, transport = MID_DEFAULTS.get(mid, MID_DEFAULTS["기타"])
    return {
        "item": name,
        "major": major, "mid": mid, "minor": minor,
        "season_months": season,
        "prefer": prefer,
        "freshness": fresh,
        "difficulty": difficulty,
        "convenience": convenience,
        "prep": prep, "purpose": purpose,
        "sensitivity": {"fx": fx, "weather": weather, "transport": transport},
        "known": name in ITEMS,
    }


def tree(names: list[str]) -> list[dict[str, Any]]:
    """
    실제 데이터에 있는 품목만으로 분류 나무를 만든다.

    카탈로그 전체를 보여주지 않는 이유 — 가격이 없는 품목을 눌렀는데
    빈 화면이 나오면 그것은 고장으로 보인다. 있는 것만 보여준다.
    """
    out: dict[str, dict[str, Any]] = {}
    for n in names:
        i = info(n)
        maj = out.setdefault(i["major"], {"name": i["major"], "count": 0, "children": {}})
        mid = maj["children"].setdefault(i["mid"], {"name": i["mid"], "count": 0, "children": {}})
        mnr = mid["children"].setdefault(i["minor"], {"name": i["minor"], "count": 0, "items": []})
        maj["count"] += 1
        mid["count"] += 1
        mnr["count"] += 1
        mnr["items"].append(n)

    def by_count(d: dict[str, Any]) -> list[dict[str, Any]]:
        return sorted(d.values(), key=lambda x: (-x["count"], x["name"]))

    return [
        {"name": maj["name"], "count": maj["count"], "children": [
            {"name": mid["name"], "count": mid["count"], "children": [
                {"name": mnr["name"], "count": mnr["count"], "items": sorted(mnr["items"])}
                for mnr in by_count(mid["children"])
            ]}
            for mid in by_count(maj["children"])
        ]}
        for maj in by_count(out)
    ]


